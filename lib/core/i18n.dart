import '../services/wallpaper_store.dart';

class I18n {
  static String lang = 'bn';
}

String t(String key) => strings[I18n.lang]?[key] ?? strings['en']![key] ?? key;

/// {name} আকারের জায়গায় মান বসায়: tf('wp_count', {'n': '5'})
String tf(String key, Map<String, String> args) {
  var s = t(key);
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

String twoDigits(int n) => n.toString().padLeft(2, '0');

String formatTime(DateTime d, bool use24) {
  if (use24) return '${twoDigits(d.hour)}:${twoDigits(d.minute)}';
  final h = d.hour % 12 == 0 ? 12 : d.hour % 12;
  return '$h:${twoDigits(d.minute)}';
}

String amPm(DateTime d) => t(d.hour < 12 ? 'am' : 'pm');

String formatDate(DateTime d) {
  final weekday = t('wd_${d.weekday}');
  final month = t('mo_${d.month}');
  return I18n.lang == 'bn' ? '$weekday, ${d.day} $month' : '$weekday, $month ${d.day}';
}

/// ওয়ালপেপারের দেখানোর নাম: অ্যাপের ছবি → অনুবাদ; নিজের ছবি → ফাইলের নাম (সময়ের অংশ বাদে)
String wallpaperName(String id, bool bundled) {
  if (bundled) return t(WallpaperStore.bundled[id]?.$1 ?? id);
  var name = id.replaceFirst(RegExp(r'^\d+_'), '');
  final dot = name.lastIndexOf('.');
  if (dot > 0) name = name.substring(0, dot);
  name = name.replaceAll('_', ' ').trim();
  return name.isEmpty ? t('wp_my_photo') : name;
}

